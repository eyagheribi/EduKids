/** decimal Math.Round(value, digits) uses banker's rounding (MidpointRounding.ToEven). */
export function roundHalfEven(value: number, digits: number): number {
  const factor = 10 ** digits;
  const scaled = value * factor;
  const floor = Math.floor(scaled);
  const diff = scaled - floor;
  const epsilon = 1e-9;
  let rounded: number;
  if (Math.abs(diff - 0.5) < epsilon) rounded = floor % 2 === 0 ? floor : floor + 1;
  else rounded = Math.round(scaled);
  return rounded / factor;
}

function normalizedAverage(list: readonly DemoCompletedSession[]): number {
  const scoreable = list.filter(
    (s) => (s.finalMaxScore ?? 0) > 0 && s.finalScore >= 0 && s.finalScore <= (s.finalMaxScore ?? 0),
  );
  if (!scoreable.length) return 0;
  const avg = scoreable.reduce((sum, s) => sum + s.finalScore / (s.finalMaxScore ?? 1), 0) / scoreable.length;
  return roundHalfEven(avg, 4);
}

function toSummary(s: DemoCompletedSession): SessionSummaryDto {
  return {
    sessionId: s.sessionId,
    gameId: s.gameId,
    gameTitle: s.gameTitle,
    gameType: s.gameType,
    finalStatus: s.finalStatus,
    attemptsUsed: s.attemptsUsed,
    maxAttempts: s.maxAttempts,
    finalScore: s.finalScore,
    finalMaxScore: s.finalMaxScore,
    startedAt: s.startedAt,
    completedAt: s.completedAt,
    nextAvailableAt: s.nextAvailableAt,
  };
}

function byCompletedDesc(a: DemoCompletedSession, b: DemoCompletedSession): number {
  return Date.parse(b.completedAt) - Date.parse(a.completedAt) || a.sessionId.localeCompare(b.sessionId);
}

// ─────────────────────────────────────────────────────────────────────────────
// DEMONSTRATION ADAPTER — replaces Suivi.Api while it cannot authenticate EduKids users.
// Same computations as ProgressService (src/Suivi.Api/Application/ProgressService.cs), applied to
// the sessions completed through DemoGamesGateway (or generated by DemoDataService).
// ─────────────────────────────────────────────────────────────────────────────
@Injectable({ providedIn: 'root' })
export class DemoProgressGateway extends ProgressGateway {
  readonly mode = 'demo' as const;
  private readonly store = inject(DemoStore);
  private readonly latency = inject(APP_CONFIG).demo.latencyMs;

  summary(spaceId: string): Observable<SpaceSummaryDto> {
    return this.run(() => {
      const list = this.sessions(spaceId);
      const total = list.length;
      const successful = list.filter((s) => s.finalStatus === 'SUCCESS').length;
      return {
        spaceId,
        totalSessions: total,
        successfulSessions: successful,
        failedSessions: list.filter((s) => s.finalStatus === 'FAILED').length,
        unfinishedSessions: list.filter((s) => s.finalStatus === 'UNFINISHED').length,
        successRate: total ? roundHalfEven((successful / total) * 100, 2) : 0,
        averageAttemptsPerSession: total
          ? roundHalfEven(list.reduce((sum, s) => sum + s.attemptsUsed, 0) / total, 2)
          : 0,
        averageNormalizedScore: normalizedAverage(list),
      };
    });
  }

  history(spaceId: string, query: HistoryQuery): Observable<PagedResult<SessionSummaryDto>> {
    return this.run(() => {
      const pageSize = Math.min(HISTORY_MAX_PAGE_SIZE, Math.max(1, query.pageSize ?? 20));
      const page = Math.max(1, query.page ?? 1);
      const from = query.from ? Date.parse(query.from) : null;
      const to = query.to ? Date.parse(query.to) : null;
      const filtered = this.sessions(spaceId)
        .filter((s) => !query.gameType || s.gameType === query.gameType)
        .filter((s) => !query.finalStatus || s.finalStatus === query.finalStatus)
        .filter((s) => from === null || Date.parse(s.completedAt) >= from)
        .filter((s) => to === null || Date.parse(s.completedAt) <= to)
        .sort(byCompletedDesc);
      if (query.sortOrder === 'asc') filtered.reverse();
      const items = filtered.slice((page - 1) * pageSize, page * pageSize).map(toSummary);
      return {
        items,
        page,
        pageSize,
        totalCount: filtered.length,
        totalPages: Math.ceil(filtered.length / pageSize),
      };
    });
  }

  gameHistory(spaceId: string, gameId: string): Observable<SessionSummaryDto[]> {
    return this.run(() =>
      this.sessions(spaceId)
        .filter((s) => s.gameId === gameId)
        .sort(byCompletedDesc)
        .map(toSummary),
    );
  }

  sessionDetail(spaceId: string, sessionId: string): Observable<SessionDetailDto> {
    return this.run(() => {
      const s = this.sessions(spaceId).find((x) => x.sessionId === sessionId);
      if (!s) throw new ApiError('Session introuvable.', 404, 'suivi');
      return {
        ...toSummary(s),
        spaceId: s.spaceId,
        gameContentSnapshot: s.gameContentSnapshot,
        attempts: [...s.attempts].sort((a, b) => a.attemptNumber - b.attemptNumber),
      };
    });
  }

  statsByType(spaceId: string): Observable<GameTypeStatsDto[]> {
    return this.run(() => {
      const groups = new Map<GameType, DemoCompletedSession[]>();
      for (const s of this.sessions(spaceId)) groups.set(s.gameType, [...(groups.get(s.gameType) ?? []), s]);
      return [...groups.entries()]
        .map(([gameType, list]) => {
          const total = list.length;
          const successful = list.filter((s) => s.finalStatus === 'SUCCESS').length;
          return {
            gameType,
            totalSessions: total,
            successfulSessions: successful,
            failedSessions: list.filter((s) => s.finalStatus === 'FAILED').length,
            unfinishedSessions: list.filter((s) => s.finalStatus === 'UNFINISHED').length,
            successRate: total ? roundHalfEven((successful / total) * 100, 2) : 0,
            averageNormalizedScore: normalizedAverage(list),
          };
        })
        .sort((a, b) => a.gameType.localeCompare(b.gameType));
    });
  }

  private sessions(spaceId: string): DemoCompletedSession[] {
    return this.store.read().completed.filter((s) => s.spaceId === spaceId);
  }

  private run<T>(operation: () => T): Observable<T> {
    return defer(() => {
      try {
        return of(operation());
      } catch (error) {
        return throwError(() =>
          error instanceof ApiError ? error : new ApiError('Erreur de démonstration.', 500, 'suivi'),
        );
      }
    }).pipe(delay(this.latency));
  }
}
